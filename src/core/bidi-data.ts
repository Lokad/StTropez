export function bidiClass(codepoint: number): BidiClass {
    if (!Number.isInteger(codepoint) || codepoint < 0 || codepoint > 0x10ffff) throw new RangeError("Invalid Unicode code point.");
    let low = 0, high = ranges.length / 2;
    while (low + 1 < high) { const mid = (low + high) >>> 1; if (ranges[mid * 2]! <= codepoint) low = mid; else high = mid; }
    return kinds[ranges[low * 2 + 1]!]!;
}
